# The complete vector set does not fit in the nRF9151 non-secure partition, so a subset
# is used. ShortMsg vectors (0 to block size bytes) are kept when shorter than
# SHORT_MSG_STRIDE, a multiple of SHORT_MSG_STRIDE, or adjacent to the length at which
# the padding no longer fits in the final block or the block size itself. The LongMsg
# files contain 64-128 vectors of up to 14 kB each, so only the shortest and the
# longest up to LONG_MSG_MAX_BYTES are used.
SHORT_MSG_STRIDE = 8
LONG_MSG_MAX_BYTES = 1536
# Monte Carlo checkpoints to validate (each is 1000 hash operations)
MCT_CHECKPOINTS = 10

# Wycheproof valid vectors with messages longer than this, only every Nth is used
WYCHEPROOF_LONG_MSG = 32
WYCHEPROOF_LONG_STRIDE = 3


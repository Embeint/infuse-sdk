def hkdf(algo: str, ikm: bytes, salt: bytes, info: bytes, length: int) -> bytes:
    """RFC 5869 HKDF"""
    prk = hmac.new(salt or bytes(hashlib.new(algo).digest_size), ikm, algo).digest()
    okm, t = b"", b""
    for i in range((length + len(prk) - 1) // len(prk)):
        t = hmac.new(prk, t + info + bytes([i + 1]), algo).digest()
        okm += t
    return okm[:length]


# clang-format column limit, and the tab width used to measure it
COLUMN_LIMIT = 100
TAB_WIDTH = 8


def c_comment(text: str) -> str:
    """Comment for a vector, indented by one tab, in the Zephyr block comment style"""
    text = " ".join(text.replace("*/", "* /").split())
    if TAB_WIDTH + len(f"/* {text} */") <= COLUMN_LIMIT:
        return f"\t/* {text} */"
    # Too long for one line, clang-format would wrap it without the leading '*'
    lines = textwrap.wrap(text, COLUMN_LIMIT - TAB_WIDTH - len(" * "))
    return "\t/*\n" + "".join(f"\t * {line}\n" for line in lines) + "\t */"


def c_bytes(data: bytes, indent: str) -> str:
    if len(data) == 0:
        return '(const uint8_t *)""'
    lines = []
    for i in range(0, len(data), 12):
        lines.append('"' + "".join(f"\\x{b:02x}" for b in data[i : i + 12]) + '"')
    return "(const uint8_t *)" + ("\n" + indent + "\t").join(lines)


def parse_rsp(path: pathlib.Path) -> list[dict]:
    records = []
    current = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith("#") or line.startswith("[") or "=" not in line:
            continue
        key, value = (x.strip() for x in line.split("=", 1))
        current[key] = value
        if key == "MD":
            records.append(current)
            current = {"Seed": current["Seed"]} if "Seed" in current else {}
    return records


def find_rsp(root: pathlib.Path, name: str) -> pathlib.Path:
    matches = list(root.rglob(name))
    if len(matches) != 1:
        raise FileNotFoundError(f"Expected exactly one {name} under {root}")
    return matches[0]


def mct_sha2(algo: str, seed: bytes, count: int) -> list[bytes]:
    out = []
    for _ in range(count):
        md = [seed, seed, seed]
        for _ in range(1000):
            md = [md[1], md[2], hashlib.new(algo, md[0] + md[1] + md[2]).digest()]
        seed = md[2]
        out.append(seed)
    return out


def mct_sha3(algo: str, seed: bytes, count: int) -> list[bytes]:
    out = []
    for _ in range(count):
        for _ in range(1000):
            seed = hashlib.new(algo, seed).digest()
        out.append(seed)
    return out


def generate_sha(rsp_dir: pathlib.Path) -> tuple[str, int]:
    out = [HEADER]
    total = 0

    for name, alg, prefix, algo, mct_type, block, pad in HASHES:
        kconfig = f"PSA_WANT_ALG_{alg}"
        ident = prefix.lower()
        vectors = []
        boundaries = {block - pad - 1, block - pad, block - pad + 1, block - 1, block}

        short = parse_rsp(find_rsp(rsp_dir, f"{prefix}ShortMsg.rsp"))
        short = [
            v
            for v in short
            if (n := int(v["Len"]) // 8) < SHORT_MSG_STRIDE or n % SHORT_MSG_STRIDE == 0 or n in boundaries
        ]
        long = parse_rsp(find_rsp(rsp_dir, f"{prefix}LongMsg.rsp"))
        long = [v for v in long if int(v["Len"]) // 8 <= LONG_MSG_MAX_BYTES]
        long = [long[0], long[-1]]

        for v in short + long:
            msg = bytes.fromhex(v["Msg"])[: int(v["Len"]) // 8]
            md = bytes.fromhex(v["MD"])
            assert hashlib.new(algo, msg).digest() == md, f"{name} vector mismatch"
            vectors.append((msg, md))
            total += len(msg) + len(md)

        monte = parse_rsp(find_rsp(rsp_dir, f"{prefix}Monte.rsp"))
        seed = bytes.fromhex(monte[0]["Seed"] if "Seed" in monte[0] else monte[0]["Msg"])
        checkpoints = [bytes.fromhex(v["MD"]) for v in monte[:MCT_CHECKPOINTS]]
        fn = mct_sha2 if mct_type == "SHA2" else mct_sha3
        assert fn(algo, seed, MCT_CHECKPOINTS) == checkpoints, f"{name} MCT mismatch"
        total += len(seed) + sum(len(c) for c in checkpoints)

        out.append(f"#ifdef CONFIG_{kconfig}\n")
        out.append(f"/* {name}: {len(short)} ShortMsg, {len(long)} LongMsg vectors */")
        out.append(f"static const struct hash_vector {ident}_vectors[] = {{")
        for msg, md in vectors:
            out.append("\t{")
            out.append(f"\t\t.msg = {c_bytes(msg, chr(9) * 2)},")
            out.append(f"\t\t.msg_len = {len(msg)},")
            out.append(f"\t\t.md = {c_bytes(md, chr(9) * 2)},")
            out.append("\t},")
        out.append("};\n")
        out.append(f"/* {name}: Monte Carlo test, first {len(checkpoints)} checkpoints */")
        out.append(f"static const uint8_t {ident}_mct_checkpoints[] = {{")
        for c in checkpoints:
            out.append("\t" + ", ".join(f"0x{b:02x}" for b in c) + ",")
        out.append("};\n")
        out.append(f"static const uint8_t {ident}_mct_seed[] = {{")
        out.append("\t" + ", ".join(f"0x{b:02x}" for b in seed) + ",")
        out.append("};")
        out.append(f"#endif /* CONFIG_{kconfig} */\n")

    out.append("const struct hash_suite hash_suites[] = {")
    for name, alg, prefix, _, mct_type, _, _ in HASHES:
        kconfig = f"PSA_WANT_ALG_{alg}"
        ident = prefix.lower()
        psa_alg = f"PSA_ALG_{alg}"
        out.append(f"#ifdef CONFIG_{kconfig}")
        out.append("\t{")
        out.append(f'\t\t.name = "{name}",')
        out.append(f"\t\t.alg = {psa_alg},")
        out.append(f"\t\t.vectors = {ident}_vectors,")
        out.append(f"\t\t.num_vectors = ARRAY_SIZE({ident}_vectors),")
        out.append(f"\t\t.mct_type = MCT_{mct_type},")
        out.append(f"\t\t.mct_seed = {ident}_mct_seed,")
        out.append(f"\t\t.mct_seed_len = sizeof({ident}_mct_seed),")
        out.append(f"\t\t.mct_checkpoints = {ident}_mct_checkpoints,")
        out.append(f"\t\t.mct_num_checkpoints = {MCT_CHECKPOINTS},")
        out.append("\t},")
        out.append(f"#endif /* CONFIG_{kconfig} */")
    out.append("};\n")
    out.append("const size_t hash_suites_num = ARRAY_SIZE(hash_suites);")
    return "\n".join(out) + "\n", total


def generate_chachapoly(wycheproof: pathlib.Path) -> tuple[str, int]:
    data = json.loads(wycheproof.read_text())
    tests = [RFC8439_A5]
    long_count = 0
    for group in data["testGroups"]:
        # PSA only supports the 96 bit nonce variant
        if group["ivSize"] != 96 or group["keySize"] != 256 or group["tagSize"] != 128:
            continue
        for t in group["tests"]:
            assert t["result"] in ("valid", "invalid")
            if t["result"] == "invalid":
                # Only modified tags are expected for the supported nonce size
                assert t["flags"] == ["ModifiedTag"], t
            elif len(t["msg"]) // 2 > WYCHEPROOF_LONG_MSG:
                long_count += 1
                if long_count % WYCHEPROOF_LONG_STRIDE:
                    continue
            t = dict(t)
            t["comment"] = f"Wycheproof {t['tcId']}" + (f": {t['comment']}" if t["comment"] else "")
            tests.append(t)

    out = [HEADER]
    out.append(f"/* RFC 8439 A.5 and {len(tests) - 1} Project Wycheproof vectors */")
    out.append("const struct aead_vector chachapoly_vectors[] = {")
    total = 0
    for t in tests:
        key, nonce, aad = (bytes.fromhex(t[k]) for k in ("key", "iv", "aad"))
        msg, ct, tag = (bytes.fromhex(t[k]) for k in ("msg", "ct", "tag"))
        valid = t["result"] == "valid"
        try:
            ChaCha20Poly1305(key).decrypt(nonce, ct + tag, aad)
            decrypted = True
        except InvalidTag:
            decrypted = False
        assert decrypted == valid, t["comment"]
        if valid:
            assert ChaCha20Poly1305(key).encrypt(nonce, msg, aad) == ct + tag
        total += len(key) + len(nonce) + len(aad) + len(msg) + len(ct) + len(tag)

        out.append(c_comment(t["comment"]))
        out.append("\t{")
        out.append(f"\t\t.key = {c_bytes(key, chr(9) * 2)},")
        out.append(f"\t\t.nonce = {c_bytes(nonce, chr(9) * 2)},")
        out.append(f"\t\t.aad = {c_bytes(aad, chr(9) * 2)},")
        out.append(f"\t\t.aad_len = {len(aad)},")
        out.append(f"\t\t.msg = {c_bytes(msg, chr(9) * 2)},")
        out.append(f"\t\t.msg_len = {len(msg)},")
        out.append(f"\t\t.ct_tag = {c_bytes(ct + tag, chr(9) * 2)},")
        out.append(f"\t\t.valid = {'true' if valid else 'false'},")
        out.append("\t},")
    out.append("};\n")
    out.append("const size_t chachapoly_vectors_num = ARRAY_SIZE(chachapoly_vectors);")
    return "\n".join(out) + "\n", total


def generate_mac() -> tuple[str, int]:
    # Validate the transcribed inputs against the published outputs
    rfc4231 = {
        0: "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7",
        1: "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843",
    }
    for idx, mac in rfc4231.items():
        _, key, data = HMAC_INPUTS[idx]
        assert hmac.new(key, data, "sha256").hexdigest() == mac, "RFC 4231 mismatch"
    rfc5869 = {
        0: "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865",
        2: "8da4e775a563c18f715f802a063c5a31b8a11f5c5ee1879ec3454e5f3c738d2d9d201395faa4b61a96c8",
    }
    for idx, okm in rfc5869.items():
        _, ikm, salt, info, length = HKDF_INPUTS[idx]
        assert hkdf("sha256", ikm, salt, info, length).hex() == okm, "RFC 5869 mismatch"

    out = [HEADER]
    total = 0

    out.append("#ifdef CONFIG_PSA_WANT_ALG_HMAC\n")
    out.append("const struct mac_input mac_inputs[] = {")
    for comment, key, data in HMAC_INPUTS:
        out.append(c_comment(comment))
        out.append("\t{")
        out.append(f"\t\t.key = {c_bytes(key, chr(9) * 2)},")
        out.append(f"\t\t.key_len = {len(key)},")
        out.append(f"\t\t.data = {c_bytes(data, chr(9) * 2)},")
        out.append(f"\t\t.data_len = {len(data)},")
        out.append("\t},")
        total += len(key) + len(data)
    out.append("};\n")
    out.append("const size_t mac_inputs_num = ARRAY_SIZE(mac_inputs);\n")
    out.append("const struct mac_suite mac_suites[] = {")
    for name, alg, algo in MAC_HASHES:
        macs = b"".join(hmac.new(key, data, algo).digest() for _, key, data in HMAC_INPUTS)
        total += len(macs)
        out.append(f"#ifdef CONFIG_PSA_WANT_ALG_{alg}")
        out.append("\t{")
        out.append(f'\t\t.name = "HMAC-{name}",')
        out.append(f"\t\t.alg = PSA_ALG_HMAC(PSA_ALG_{alg}),")
        out.append(f"\t\t.macs = {c_bytes(macs, chr(9) * 2)},")
        out.append("\t},")
        out.append(f"#endif /* CONFIG_PSA_WANT_ALG_{alg} */")
    out.append("};\n")
    out.append("const size_t mac_suites_num = ARRAY_SIZE(mac_suites);\n")
    out.append("#endif /* CONFIG_PSA_WANT_ALG_HMAC */\n")

    out.append("#ifdef CONFIG_PSA_WANT_ALG_HKDF\n")
    out.append("const struct kdf_input kdf_inputs[] = {")
    for comment, ikm, salt, info, length in HKDF_INPUTS:
        out.append(c_comment(comment))
        out.append("\t{")
        out.append(f"\t\t.ikm = {c_bytes(ikm, chr(9) * 2)},")
        out.append(f"\t\t.ikm_len = {len(ikm)},")
        out.append(f"\t\t.salt = {c_bytes(salt, chr(9) * 2)},")
        out.append(f"\t\t.salt_len = {len(salt)},")
        out.append(f"\t\t.info = {c_bytes(info, chr(9) * 2)},")
        out.append(f"\t\t.info_len = {len(info)},")
        out.append(f"\t\t.okm_len = {length},")
        out.append("\t},")
        total += len(ikm) + len(salt) + len(info)
    out.append("};\n")
    out.append("const size_t kdf_inputs_num = ARRAY_SIZE(kdf_inputs);\n")
    out.append("const struct kdf_suite kdf_suites[] = {")
    for name, alg, algo in MAC_HASHES:
        okms = b"".join(hkdf(algo, *v[1:]) for v in HKDF_INPUTS)
        total += len(okms)
        out.append(f"#ifdef CONFIG_PSA_WANT_ALG_{alg}")
        out.append("\t{")
        out.append(f'\t\t.name = "HKDF-{name}",')
        out.append(f"\t\t.alg = PSA_ALG_HKDF(PSA_ALG_{alg}),")
        out.append(f"\t\t.okms = {c_bytes(okms, chr(9) * 2)},")
        out.append("\t},")
        out.append(f"#endif /* CONFIG_PSA_WANT_ALG_{alg} */")
    out.append("};\n")
    out.append("const size_t kdf_suites_num = ARRAY_SIZE(kdf_suites);\n")
    out.append("#endif /* CONFIG_PSA_WANT_ALG_HKDF */")
    return "\n".join(out) + "\n", total


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0], allow_abbrev=False)
    parser.add_argument("rsp_dir", type=pathlib.Path, help="Directory of NIST CAVP .rsp files")
    parser.add_argument("wycheproof", type=pathlib.Path, help="chacha20_poly1305_test.json")
    args = parser.parse_args()

    src = pathlib.Path(__file__).resolve().parent.parent / "src"
    sha, sha_total = generate_sha(args.rsp_dir)
    chachapoly, chachapoly_total = generate_chachapoly(args.wycheproof)
    mac, mac_total = generate_mac()
    outputs = [src / "vectors_sha.c", src / "vectors_chachapoly.c", src / "vectors_mac.c"]
    outputs[0].write_text(sha)
    outputs[1].write_text(chachapoly)
    outputs[2].write_text(mac)
    # Generated code must match the repository formatting
    subprocess.run(["clang-format", "-i", *outputs], check=True)
    print(
        f"SHA vectors: {sha_total} bytes, ChaCha20-Poly1305 vectors: {chachapoly_total} bytes, "
        f"HMAC/HKDF vectors: {mac_total} bytes"
    )


if __name__ == "__main__":
    main()

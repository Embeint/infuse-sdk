"""Generate the test vector sources for the PSA crypto test.

SHA-2 and SHA-3 vectors are taken from the NIST CAVP byte-oriented response files:
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/shs/shabytetestvectors.zip
  https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Algorithm-Validation-Program/documents/sha3/sha-3bytetestvectors.zip

NIST does not publish ChaCha20-Poly1305 vectors, so the RFC 8439 vectors and the
Project Wycheproof vectors (96 bit nonce) are used instead:
  https://raw.githubusercontent.com/C2SP/wycheproof/main/testvectors_v1/chacha20_poly1305_test.json

HMAC vectors use the RFC 4231 inputs, and HKDF vectors the RFC 5869 inputs, with
additional inputs exercising multiple blocks. Expected outputs for every hash are
computed with the Python standard library, after validating the published RFC outputs.

Usage:
  generate_vectors.py <directory containing extracted .rsp files> <wycheproof json>
"""

